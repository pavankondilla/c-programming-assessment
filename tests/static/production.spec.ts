import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('built static app runs C, loads no external resources, submits, and opens examiner review under a subdirectory', async ({ page }) => {
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  page.on('request', r => { if (r.url().startsWith('http') && !r.url().startsWith('http://127.0.0.1:4173')) external.push(r.url()); });
  await page.goto('./');
  await page.getByLabel('Name', { exact: true }).fill('trainee');
  await page.getByLabel('Password', { exact: true }).fill('CExam@123');
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.getByRole('button', { name: 'Start Examination' }).click();
  const code = '#include <stdio.h>\n#include <stdlib.h>\nint main(void) {\n    int *value = malloc(sizeof(int));\n    if (!value || scanf("%d", value) != 1) return 1;\n    FILE *fp = fopen("student.txt", "w");\n    if (!fp) return 2;\n    fprintf(fp, "%d", *value);\n    fclose(fp);\n    free(value);\n    fp = fopen("student.txt", "r");\n    if (!fp) return 3;\n    int ch;\n    while ((ch = fgetc(fp)) != EOF) putchar(ch);\n    fclose(fp);\n    return 0;\n}';
  await page.getByRole('textbox', { name: 'Code answer for question 1', exact: true }).fill(code);
  await page.getByLabel('Standard input', { exact: false }).fill('42\n');
  await page.getByRole('button', { name: 'Run Code', exact: true }).click();
  await expect(page.getByText('Last run: Run completed', { exact: true })).toBeVisible({ timeout: 100000 });
  await expect(page.getByLabel('Standard output', { exact: true })).toHaveText('42');
  let data = await page.evaluate(() => JSON.parse(localStorage.getItem('c-assessment.store.v1')!));
  expect(Object.values(data.attempts[0].review.scores).every(s => s === null)).toBe(true);
  expect(data.attempts[0].submittedAt).toBeNull();
  const access = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(access.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) }))).toEqual([]);
  await page.evaluate(() => { (document.activeElement as HTMLElement | null)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'docs/screenshots/exam-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => { (document.activeElement as HTMLElement | null)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'docs/screenshots/exam-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 720 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Submit Exam' }).click();
  await page.getByRole('button', { name: 'Confirm Submission' }).click();
  await expect(page.getByRole('heading', { name: 'Your work is submitted.' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.evaluate(() => { (document.activeElement as HTMLElement | null)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'docs/screenshots/login-desktop.png', fullPage: true });
  await page.getByLabel('Name', { exact: true }).fill('charan');
  await page.getByLabel('Password', { exact: true }).fill('Review@123');
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(page.getByLabel('Submitted code for question 1', { exact: true })).toContainText('#include');
  expect(errors).toEqual([]); expect(external).toEqual([]);
});
